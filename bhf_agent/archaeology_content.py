def _details(
    description: str,
    discovery_context: str,
    physical_description: str,
    evidence_summary: str,
    biblical_relevance: str,
    caution: str,
    *,
    date_display: str,
    dating_basis: str = "Historical and archaeological dating",
    scholarly_context: str = "",
    discovery_year: str = "",
    current_location: str = "",
    dispute_status: str = "not_disputed",
    external_references: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    details: dict[str, Any] = {
        "description": description,
        "discovery_context": discovery_context,
        "date_display": date_display,
        "dating_basis": dating_basis,
        "physical_description": physical_description,
        "evidence_summary": evidence_summary,
        "biblical_relevance": biblical_relevance,
        "scholarly_context": scholarly_context,
        "interpretive_caution": caution,
        "discovery_year": discovery_year,
        "current_location": current_location,
        "dispute_status": dispute_status,
    }
    if external_references:
        details["external_references"] = external_references
    return details


